def test_dependsOn_orders_activities(
    artifacts_root: Path, metadata_db: Path, tmp_path: Path
) -> None:
    """If activity B dependsOn A, A must run first even when listed second."""
    pipeline = {
        "name": "PL_TEST",
        "properties": {
            "activities": [
                {
                    "name": "B",
                    "type": "SetVariable",
                    "dependsOn": [{"activity": "A", "dependencyConditions": ["Succeeded"]}],
                    "typeProperties": {"variableName": "v_b", "value": "second"},
                },
                {
                    "name": "A",
                    "type": "SetVariable",
                    "typeProperties": {"variableName": "v_a", "value": "first"},
                },
            ],
            "variables": {"v_a": {"type": "String"}, "v_b": {"type": "String"}},
        },
    }
    _write_json(artifacts_root / "pipelines" / "PL_TEST.json", pipeline)

    runner, ctx = _ctx(artifacts_root, metadata_db, tmp_path)
    result = runner.run_pipeline(pipeline_name="PL_TEST", parameters={}, ctx=ctx)

    assert result.status == "Succeeded"
    # Both activities ran in dependency order
    assert [r.output.get("variable") for r in result.activity_results] == ["v_a", "v_b"]


def test_failed_dependency_skips_dependents(
    artifacts_root: Path, metadata_db: Path, tmp_path: Path
) -> None:
    """If A fails, B (dependsOn A=Succeeded) is Skipped not run."""
    pipeline = {
        "name": "PL_TEST",
        "properties": {
            "activities": [
                # A intentionally references an undefined variable to fail
                {
                    "name": "A",
                    "type": "SetVariable",
                    "typeProperties": {
                        "variableName": "undeclared_variable",
                        "value": "@variables('does_not_exist')",
                    },
                },
                {
                    "name": "B",
                    "type": "SetVariable",
                    "dependsOn": [{"activity": "A", "dependencyConditions": ["Succeeded"]}],
                    "typeProperties": {"variableName": "v_b", "value": "ran"},
                },
            ],
            "variables": {"v_b": {"type": "String"}},
        },
    }
    _write_json(artifacts_root / "pipelines" / "PL_TEST.json", pipeline)

    runner, ctx = _ctx(artifacts_root, metadata_db, tmp_path)
    result = runner.run_pipeline(pipeline_name="PL_TEST", parameters={}, ctx=ctx)

    assert result.status == "Failed"
    statuses = [r.status for r in result.activity_results]
    assert "Failed" in statuses
    assert "Skipped" in statuses


