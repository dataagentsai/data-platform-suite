def test_switch_dispatches_matching_case(
    artifacts_root: Path, metadata_db: Path, tmp_path: Path
) -> None:
    pipeline = {
        "name": "PL_TEST",
        "properties": {
            "parameters": {"src_type": {"type": "String", "defaultValue": "postgres"}},
            "activities": [
                {
                    "name": "RouteBySource",
                    "type": "Switch",
                    "typeProperties": {
                        "on": {
                            "type": "Expression",
                            "value": "@pipeline().parameters.src_type",
                        },
                        "cases": [
                            {
                                "value": "postgres",
                                "activities": [
                                    {
                                        "name": "PgPath",
                                        "type": "SetVariable",
                                        "typeProperties": {
                                            "variableName": "chosen",
                                            "value": "pg",
                                        },
                                    }
                                ],
                            },
                            {
                                "value": "mysql",
                                "activities": [
                                    {
                                        "name": "MyPath",
                                        "type": "SetVariable",
                                        "typeProperties": {
                                            "variableName": "chosen",
                                            "value": "my",
                                        },
                                    }
                                ],
                            },
                        ],
                        "defaultActivities": [],
                    },
                }
            ],
            "variables": {"chosen": {"type": "String"}},
        },
    }
    _write_json(artifacts_root / "pipelines" / "PL_TEST.json", pipeline)

    runner, ctx = _ctx(artifacts_root, metadata_db, tmp_path)
    result = runner.run_pipeline(pipeline_name="PL_TEST", parameters={}, ctx=ctx)

    assert result.status == "Succeeded"
    assert result.activity_results[0].output["branch"] == "postgres"
