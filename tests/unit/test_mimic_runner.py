def test_execute_pipeline_recursion_preserves_parent_run(
    artifacts_root: Path, metadata_db: Path, tmp_path: Path
) -> None:
    child = {
        "name": "PL_CHILD",
        "properties": {
            "parameters": {"x": {"type": "String"}},
            "activities": [
                {
                    "name": "EchoX",
                    "type": "SetVariable",
                    "typeProperties": {
                        "variableName": "echoed",
                        "value": {"type": "Expression", "value": "@pipeline().parameters.x"},
                    },
                }
            ],
            "variables": {"echoed": {"type": "String"}},
        },
    }
    parent = {
        "name": "PL_PARENT",
        "properties": {
            "activities": [
                {
                    "name": "RunChild",
                    "type": "ExecutePipeline",
                    "typeProperties": {
                        "pipeline": {
                            "referenceName": "PL_CHILD",
                            "type": "PipelineReference",
                        },
                        "parameters": {"x": "hello"},
                    },
                }
            ]
        },
    }
    _write_json(artifacts_root / "pipelines" / "PL_CHILD.json", child)
    _write_json(artifacts_root / "pipelines" / "PL_PARENT.json", parent)

    runner, ctx = _ctx(artifacts_root, metadata_db, tmp_path)
    result = runner.run_pipeline(pipeline_name="PL_PARENT", parameters={}, ctx=ctx)

    assert result.status == "Succeeded"
    assert result.activity_results[0].output["child_pipeline"] == "PL_CHILD"


