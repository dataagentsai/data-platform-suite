def test_run_log_started_emulation_inserts_row(
    artifacts_root: Path, metadata_db: Path, tmp_path: Path
) -> None:
    pipeline = {
        "name": "PL_TEST",
        "properties": {
            "parameters": {"dataset_id": {"type": "String", "defaultValue": "1"}},
            "activities": [
                {
                    "name": "RunLogStarted",
                    "type": "Lookup",
                    "typeProperties": {
                        "dataset": {
                            "referenceName": "DS_METADATA_DB_QUERY",
                            "type": "DatasetReference",
                        },
                        "firstRowOnly": True,
                        "source": {
                            "type": "AzureSqlSource",
                            "sqlReaderQuery": {
                                "type": "Expression",
                                "value": (
                                    "EXEC meta.sp_run_log_started "
                                    "@dataset_id = @{pipeline().parameters.dataset_id}, "
                                    "@pipeline_name = 'PL_TEST'"
                                ),
                            },
                        },
                    },
                }
            ],
        },
    }
    _write_json(artifacts_root / "pipelines" / "PL_TEST.json", pipeline)

    runner, ctx = _ctx(artifacts_root, metadata_db, tmp_path)
    result = runner.run_pipeline(pipeline_name="PL_TEST", parameters={}, ctx=ctx)

    assert result.status == "Succeeded"
    output = result.activity_results[0].output
    assert output["firstRow"]["status"] == "STARTED"
    # Verify a row landed in run_log (SQLite has no schemas; meta. prefix
    # is stripped in the mimic — see _strip_meta_prefix).
    conn = sqlite3.connect(metadata_db)
    rows = conn.execute("SELECT pipeline_name FROM run_log").fetchall()
    conn.close()
    assert rows == [("PL_TEST",)]


