# Cost per data product and untagged spend are the separate cost tool's (decision of 4 Nov 2026); the platform only tags its
# jobs (dataplatform.governance.tables.COMPUTE_TAGS, compute_tags()).


def audit_sql(tables: Iterable[TableSpec], env: str) -> str:
    """Reads of tables with protected columns and every grant or tag change (SEC-04, DPC-0078)."""
    names = sorted(t.qualified(env) for t in tables if any(c.protected for c in t.columns))
    listed = ", ".join(lit(n) for n in names) or "''"
    return (
        HEADER
        + f"""-- Audit for {env}: who read a table holding protected columns, and who changed a grant, mask or tag.
-- Parameters :start_date and :end_date (DATE). Source: system.access.audit.
SELECT event_time, user_identity.email AS who, action_name,
       COALESCE(request_params['full_name_arg'], request_params['securable_full_name']) AS securable,
       response.status_code
FROM system.access.audit
WHERE service_name = 'unityCatalog'
  AND event_date BETWEEN :start_date AND :end_date
  AND (
    action_name IN ('updatePermissions', 'updateTables', 'createFunction', 'deleteFunction')
    OR COALESCE(request_params['full_name_arg'], request_params['securable_full_name']) IN ({listed})
  )
ORDER BY event_time DESC;
"""
    )
