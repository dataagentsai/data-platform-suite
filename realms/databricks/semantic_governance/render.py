"""Databricks rendering of the kernel's semantic, BI, governance and access definitions (product names live here).

Pure functions: kernel records in, file text out, byte-identical for the same input. Names follow ADR-012:
catalogs <env>_<layer>, gold schemas per domain, access functions in <env>_ops.access. Identifiers are checked and
back-quoted; string values are escaped; no statement takes text from outside the manifest and contracts.
"""

# ruff: noqa: S608 -- this module emits SQL text by design; identifiers pass ident(), values pass lit()
from __future__ import annotations

import hashlib
import json
import re
from collections.abc import Iterable, Sequence

from dataplatform.access.model import AccessPlan, ColumnMask, Grant, RowFilter
from dataplatform.contract import TYPES
from dataplatform.governance.catalog import Action
from dataplatform.governance.tables import TableSpec
from dataplatform.semantic.experiences import ConversationSpace, Dashboard, Tile
from dataplatform.semantic.metrics import TIME, Dimension, KnownAnswerCase, MetricView

HEADER = (
    "-- GENERATED by realms/databricks/semantic_governance/generate.py from the manifest and contracts. Do not edit.\n"
)
IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]{0,127}$")
GROUP = re.compile(r"^[a-z][a-z0-9-]{0,127}$")
MASKED_TEXT = "***"
ACCESS_SCHEMA = "access"
GRID_WIDTH = 6  # dashboard canvas columns


class RenderError(ValueError):
    pass


# ---------------------------------------------------------------------------------------------------- quoting


def ident(*parts: str) -> str:
    for p in parts:
        if not IDENT.match(p):
            raise RenderError(f"'{p}' is not a safe identifier")
    return ".".join(f"`{p}`" for p in parts)


def label(name: str) -> str:
    """A metric view's dimension or measure name ('OTIF %'), back-quoted."""
    if "`" in name or "\n" in name:
        raise RenderError(f"'{name}' cannot be a metric view field name")
    return f"`{name}`"


def lit(text: str) -> str:
    return "'" + text.replace("\\", "\\\\").replace("'", "\\'") + "'"


def principal(group: str) -> str:
    if not GROUP.match(group):
        raise RenderError(f"'{group}' is not a group name")
    return f"`{group}`"


def table(env: str, layer: str, schema: str, name: str) -> str:
    return ident(f"{env}_{layer}", schema, name)


def scalar(value: object) -> str:
    """A YAML scalar: JSON strings are valid YAML, so quoting is never guessed."""
    return json.dumps(value, ensure_ascii=False)


def stable_id(*parts: str) -> str:
    return hashlib.sha256("\x1f".join(parts).encode()).hexdigest()[:32]


# ---------------------------------------------------------------------------------------------------- metric views


def _dimension_comment(view: MetricView, d: Dimension) -> str:
    if d.conformed_from == TIME:
        used = ", ".join(m.name for m in view.measures if m.time_dimension == d.name)
        return f"Time dimension of {used}." if used else "Time dimension."
    if d.conformed_from:
        return f"From the shared dimension {d.conformed_from}, as of the event (ADR-005)."
    return f"Column of {view.source}."


def metric_view_yaml(view: MetricView, env: str, comment: str) -> str:
    lines = ["version: 1.1", f"comment: {scalar(comment)}", f"source: {env}_gold.{view.source_domain}.{view.source}"]
    if view.joins:
        lines.append("joins:")
        for j in view.joins:
            lines += [
                f"  - name: {j.name}",
                f"    source: {env}_gold.{j.domain}.{j.name}",
                f'    "on": source.{j.key} = {j.name}.{j.key}',
                "    cardinality: many_to_one",  # one dimension row per surrogate key (ADR-004): no fan-out
            ]
    lines.append("dimensions:")
    for d in view.dimensions:
        lines += [f"  - name: {scalar(d.name)}", f"    expr: {scalar(d.expr)}",
                  f"    comment: {scalar(_dimension_comment(view, d))}"]
    lines.append("measures:")
    for m in view.measures:
        note = (f"{m.description} " if m.description else "") + (
            f"Certification: {m.certification}. Additive: {'yes' if m.additive else 'no'}. "
            f"Time dimension: {m.time_dimension}."
        )
        lines += [f"  - name: {scalar(m.name)}", f"    expr: {scalar(m.expr)}", f"    comment: {scalar(note)}"]
        if m.synonyms:
            lines.append(f"    synonyms: {scalar(list(m.synonyms))}")
    return "\n".join(lines) + "\n"


def metric_view_sql(view: MetricView, env: str, comment: str) -> str:
    name = table(env, "gold", view.domain, view.name)
    return (
        HEADER + f"-- {view.name}: {'certified measures only' if view.certified_only else 'preview'} "
        f"(owner {view.owner})\nCREATE OR REPLACE VIEW {name}\nWITH METRICS\nLANGUAGE YAML\nAS $$\n"
        + metric_view_yaml(view, env, comment)
        + "$$;\n"
    )


def _where(case: KnownAnswerCase) -> str:
    fmt = {"month": "yyyy-MM", "day": "yyyy-MM-dd"}
    parts = []
    for f in case.answer.filters:
        if f.grain == "equals":
            parts.append(f"{label(f.dimension)} = {lit(f.value)}")
        else:
            parts.append(f"date_format({label(f.dimension)}, {lit(fmt[f.grain])}) = {lit(f.value)}")
    return " AND ".join(parts)


def known_answers_sql(cases: Sequence[KnownAnswerCase], views: Iterable[MetricView], env: str) -> str:
    """One row per certified known answer: expected, got from the metric view, and ok (ADR-022, SERV-06)."""
    domain = {v.name: v.domain for v in views}
    rows = []
    for c in cases:
        src = table(env, "gold", domain[c.view], c.view)
        rows.append(
            f"  SELECT {lit(c.view)} AS view_name, {lit(c.measure)} AS measure, {lit(c.label)} AS address,\n"
            f"         CAST({c.answer.value!r} AS DOUBLE) AS expected,\n"
            f"         CAST({c.answer.tolerance!r} AS DOUBLE) AS tolerance,\n"
            f"         (SELECT CAST(MEASURE({label(c.measure)}) AS DOUBLE) FROM {src} WHERE {_where(c)}) AS got"
        )
    body = "\n  UNION ALL\n".join(rows)
    return (
        HEADER + "-- Known-answer tests of the certified metrics, run against the metric views (needs gold).\n"
        "SELECT *, got IS NOT NULL AND abs(got - expected) <= tolerance AS ok FROM (\n"
        f"{body}\n) ORDER BY view_name, measure;\n"
    )


# ---------------------------------------------------------------------------------------------------- dashboards


def _slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_") or "x"


def _tile_query(t: Tile, env: str, domain: str) -> str:
    src = table(env, "gold", domain, t.view)
    if t.dimension is None:
        return f"SELECT MEASURE({label(t.measure)}) AS value FROM {src}"
    return (
        f"SELECT {label(t.dimension)} AS dimension, MEASURE({label(t.measure)}) AS value "
        f"FROM {src} GROUP BY ALL ORDER BY dimension"
    )


def _widget(t: Tile, dataset: str, time_dims: set[str]) -> dict[str, object]:
    fields = [{"name": "value", "expression": "`value`"}]
    if t.dimension is None:
        spec: dict[str, object] = {
            "version": 2,
            "widgetType": "counter",
            "encodings": {"value": {"fieldName": "value", "displayName": t.measure}},
        }
    else:
        fields.insert(0, {"name": "dimension", "expression": "`dimension`"})
        temporal = t.dimension in time_dims
        spec = {
            "version": 3,
            "widgetType": "line" if temporal else "bar",
            "encodings": {
                "x": {
                    "fieldName": "dimension",
                    "displayName": t.dimension,
                    "scale": {"type": "temporal" if temporal else "categorical"},
                },
                "y": {"fieldName": "value", "displayName": t.measure, "scale": {"type": "quantitative"}},
            },
        }
    spec["frame"] = {"showTitle": True, "title": t.title}
    return {
        "name": f"w_{dataset}",
        "queries": [{"name": "main_query", "query": {"datasetName": dataset, "fields": fields, "disaggregated": True}}],
        "spec": spec,
    }


def dashboard_json(d: Dashboard, views: Iterable[MetricView], env: str) -> str:
    """An AI/BI dashboard (.lvdash.json): a page per certified view, three tile kinds, every dataset a metric view
    query (FLOW-01: dashboards read metric views and gold only)."""
    by_name = {v.name: v for v in views}
    datasets, pages = [], []
    for p in d.pages:
        v = by_name[p.view]
        time_dims = {m.time_dimension for m in v.measures}
        layout, x, y = [], 0, 0
        for t in p.tiles:
            ds = "_".join([_slug(t.view), _slug(t.measure), t.kind, _slug(t.dimension or "all")])
            datasets.append({"name": ds, "displayName": t.title, "queryLines": [_tile_query(t, env, v.domain)]})
            width = 2 if t.kind == "counter" else 3
            if x + width > GRID_WIDTH:
                x, y = 0, y + 6
            layout.append(
                {
                    "widget": _widget(t, ds, time_dims),
                    "position": {"x": x, "y": y, "width": width, "height": 3 if t.kind == "counter" else 6},
                }
            )
            x += width
        pages.append({"name": _slug(p.view), "displayName": p.title, "pageType": "PAGE_TYPE_CANVAS", "layout": layout})
    doc = {"datasets": datasets, "pages": pages, "uiSettings": {"theme": {"widgetHeaderAlignment": "LEFT"}}}
    return json.dumps(doc, indent=2, ensure_ascii=False) + "\n"


def genie_space_json(space: ConversationSpace, views: Iterable[MetricView], env: str) -> str:
    """The Genie space: the certified views as its only tables, instructions and sample questions from the metric
    files (SERV-06, DPC-0076). `space` is the API's serialized_space before serialising; the deployer adds the
    warehouse id of the environment."""
    domain = {v.name: v.domain for v in views}
    # the Genie API refuses lists that are not sorted (tables by identifier, questions by id): found on deploy 15 Nov
    tables = sorted(({"identifier": f"{env}_gold.{domain[n]}.{n}"} for n in space.views), key=lambda t: t["identifier"])
    questions = sorted(({"id": stable_id("q", q), "question": [q]} for q in space.sample_questions),
                       key=lambda q: str(q["id"]))
    body = {
        "version": 1,
        "config": {"sample_questions": questions},
        "data_sources": {"tables": tables},
        "instructions": {
            "text_instructions": [
                {"id": stable_id("i", *space.instructions), "content": [i + "\n" for i in space.instructions]}
            ]
        },
    }
    doc = {
        "title": space.title,
        "description": f"Certified metrics only (ADR-022). Declines: {', '.join(space.declined) or 'nothing'}.",
        "warehouse_id": "${var.warehouse_id}",
        "space": body,
    }
    return json.dumps(doc, indent=2, ensure_ascii=False) + "\n"


# ---------------------------------------------------------------------------------------------------- catalog sync


def _tags(tags: Iterable[tuple[str, str]]) -> str:
    return ", ".join(f"{lit(k)} = {lit(v)}" for k, v in tags)


def catalog_action_sql(a: Action, env: str) -> str:
    target = table(env, a.ref.layer, a.ref.schema, a.ref.name)
    kind = "TABLE" if a.kind == "table" else "VIEW"
    col = f" ALTER COLUMN {ident(a.ref.column)}" if a.ref.column else ""
    if a.op == "comment":
        if a.kind != "table":
            return f"-- {a.ref.name}: the view's comment is set by its definition"
        if a.ref.column:
            return f"ALTER TABLE {target}{col} COMMENT {lit(a.comment)};"
        return f"COMMENT ON TABLE {target} IS {lit(a.comment)};"
    if a.op == "set_tags":
        return f"ALTER {kind} {target}{col} SET TAGS ({_tags(a.tags)});"
    if a.op == "unset_tags":
        return f"ALTER {kind} {target}{col} UNSET TAGS ({', '.join(lit(k) for k in a.keys)});"
    raise RenderError(f"unknown catalog action '{a.op}'")


def catalog_sync_sql(actions: Sequence[Action], env: str) -> str:
    body = "\n".join(catalog_action_sql(a, env) for a in actions) or "-- nothing to change: the catalog matches"
    return (
        HEADER + f"-- Catalog sync for {env}: owners, descriptions, glossary terms, data product and classification "
        f"tags from the contracts and manifest (DPC-0075, CAT-01). {len(actions)} action(s).\n{body}\n"
    )


# ---------------------------------------------------------------------------------------------------- access


def _grant_sql(g: Grant, env: str) -> str:
    who = principal(g.group)
    if g.scope == "catalog":
        privs = "USE CATALOG, USE SCHEMA, SELECT" if g.privilege == "read" else "USE CATALOG"
        return f"GRANT {privs} ON CATALOG {ident(f'{env}_{g.layer}')} TO {who};"
    if g.scope == "schema":
        return f"GRANT USE SCHEMA ON SCHEMA {ident(f'{env}_{g.layer}', g.schema)} TO {who};"
    return f"GRANT SELECT ON TABLE {table(env, g.layer, g.schema, g.name)} TO {who};"


def _members(groups: Iterable[str]) -> str:
    return " OR ".join(f"is_account_group_member({lit(g)})" for g in groups) or "FALSE"


def mask_function(m: ColumnMask, env: str) -> str:
    return ident(f"{env}_ops", ACCESS_SCHEMA, f"mask_{m.layer}_{m.schema}_{m.table}_{m.column}")


def _mask_sql(m: ColumnMask, env: str) -> str:
    sql_type = TYPES[m.logical_type].upper()
    hidden = lit(MASKED_TEXT) if sql_type == "STRING" else f"CAST(NULL AS {sql_type})"
    what = "the token (never detokenised)" if m.tokenised else "the stored value"
    fn = mask_function(m, env)
    return (
        f"CREATE OR REPLACE FUNCTION {fn}(v {sql_type})\nRETURNS {sql_type}\n"
        f"COMMENT {lit(f'{m.classification}: allowed groups see {what}; everyone else sees it masked')}\n"
        f"RETURN CASE WHEN {_members(m.allowed)} THEN v ELSE {hidden} END;\n"
        f"ALTER TABLE {table(env, m.layer, m.schema, m.table)} ALTER COLUMN {ident(m.column)} SET MASK {fn};"
    )


def _row_filter_sql(f: RowFilter, env: str) -> str:
    fn = ident(f"{env}_ops", ACCESS_SCHEMA, f"rows_{f.layer}_{f.schema}_{f.table}_{f.column}")
    conds = [_members(f.unrestricted)] if f.unrestricted else []
    conds += [
        f"(is_account_group_member({lit(g)}) AND v IN ({', '.join(lit(x) for x in vals)}))" for g, vals in f.limited
    ]
    return (
        f"CREATE OR REPLACE FUNCTION {fn}(v STRING)\nRETURNS BOOLEAN\n"
        f"RETURN {' OR '.join(conds) or 'FALSE'};\n"
        f"ALTER TABLE {table(env, f.layer, f.schema, f.table)} SET ROW FILTER {fn} ON ({ident(f.column)});"
    )


def access_sql(plan: AccessPlan, env: str) -> str:
    parts = [
        HEADER + f"-- Access model for {env} (DPC-0066, SEC-02, ENV-02): grants to groups only, masks on "
        "confidential and restricted columns, row filters deny by default.",
        f"CREATE SCHEMA IF NOT EXISTS {ident(f'{env}_ops', ACCESS_SCHEMA)};",
        "",
        "-- Grants",
    ]
    parts += [_grant_sql(g, env) for g in plan.grants]
    parts += ["", "-- Column masks"] + [_mask_sql(m, env) for m in plan.masks]
    if plan.row_filters:
        parts += ["", "-- Row filters"] + [_row_filter_sql(f, env) for f in plan.row_filters]
    return "\n".join(parts) + "\n"


