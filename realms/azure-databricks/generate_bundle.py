"""Generate the Databricks Asset Bundle that deploys the platform's engine job to an Azure Databricks workspace.

    uv run --no-project --with pyyaml python realms/azure-databricks/generate_bundle.py          # write
    uv run --no-project --with pyyaml python realms/azure-databricks/generate_bundle.py --check  # exit 1 if stale

Input: realms/databricks/engine/databricks.yml (the engine's bundle; not edited here). Output:
realms/azure-databricks/bundle/databricks.yml: the same jobs (engine_probe, engine_days = job `dp-<env>-engine-days`),
with paths re-pointed at the engine folder and two targets, azure-dev and azure-prod, that differ from the engine's
Free Edition target in three ways:
  * no workspace host in the file: DATABRICKS_HOST (Terraform output workspace_url) or a CLI profile selects the
    workspace, so a stray value cannot send a deploy to another workspace and no id is committed;
  * mode production, with a per-identity root path (as the first cloud's bundle), so a deploy never overwrites another
    user's copy;
  * the metadata store is the environment's Lakebase project dp-meta-<env>, and jobs carry cost-allocation tags.
Serverless compute is what the engine's jobs already use (a job with environments and no cluster spec), with the same
environment_version as on Free Edition; Unity Catalog is on by default in an Azure Databricks premium workspace.
"""
from __future__ import annotations

import argparse
import copy
import posixpath
import sys
from pathlib import Path
from typing import Any

import yaml

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
ENGINE = REPO / "realms" / "databricks" / "engine" / "databricks.yml"
OUT = HERE / "bundle" / "databricks.yml"
HEADER = ("# GENERATED by realms/azure-databricks/generate_bundle.py from realms/databricks/engine/databricks.yml. "
          "Do not edit.\n")
ENGINE_DIR = "../../databricks/engine"  # as seen from realms/azure-databricks/bundle


def repoint(path: str) -> str:
    """A path in the engine's bundle (relative to realms/databricks/engine), as seen from this bundle."""
    if path.startswith("../../../"):
        return path  # the repository root is the same distance from both folders
    return posixpath.normpath(posixpath.join(ENGINE_DIR, path))


def target(env: str) -> dict[str, Any]:
    return {
        "mode": "production",
        "variables": {"env": env, "meta_instance": f"dp-meta-{env}"},
        "workspace": {"root_path": "/Workspace/Users/${workspace.current_user.userName}/.bundle/${bundle.name}/" + env},
    }


def generate(engine: dict[str, Any]) -> dict[str, Any]:
    doc = copy.deepcopy(engine)
    doc["bundle"] = {"name": "dp_engine_azure"}
    doc["variables"] = {
        "env": {"description": "dev or prod; picks the catalogs <env>_<layer>", "default": "dev"},
        "meta_instance": {"description": "the Lakebase project that holds the metadata store (Terraform output "
                                         "metadata_store)", "default": "dp-meta-dev"},
        "cost_center": {"default": "data-platform"},
    }
    doc["sync"]["paths"] = [repoint(p) for p in engine["sync"]["paths"]]
    doc["sync"]["include"] = [repoint(i) for i in engine["sync"].get("include", [])]
    # The workspace host is not written here: DATABRICKS_HOST selects it (README, deploy order).
    doc["targets"] = {"azure-dev": {"default": True, **target("dev")}, "azure-prod": target("prod")}
    for job in doc["resources"]["jobs"].values():
        job["tags"] = {"env": "${var.env}", "cost_center": "${var.cost_center}"}
        for task in job["tasks"]:
            py = task["spark_python_task"]
            py["python_file"] = repoint(py["python_file"])
    return doc


def render() -> str:
    engine = yaml.safe_load(ENGINE.read_text())
    return HEADER + yaml.safe_dump(generate(engine), sort_keys=False, default_flow_style=False, width=120)


def main() -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--check", action="store_true", help="fail if the committed bundle differs from the engine bundle")
    a = p.parse_args()
    text = render()
    if a.check:
        if not OUT.exists() or OUT.read_text() != text:
            sys.stderr.write("stale: realms/azure-databricks/bundle/databricks.yml\n")
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    sys.stdout.write("wrote realms/azure-databricks/bundle/databricks.yml\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
