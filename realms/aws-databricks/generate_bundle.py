"""Generate the Databricks Asset Bundle for Databricks on AWS from the compiled manifests (M4: jobs are generated,
never hand-written).

    uv run --no-project --with pyyaml python realms/aws-databricks/generate_bundle.py          # write
    uv run --no-project --with pyyaml python realms/aws-databricks/generate_bundle.py --check  # exit 1 if stale

Input: realms/databricks/compiled/domains/*.json (scripts/dp_compile_domain.py: a domain, its business timezone, its
datasets and gold tables). Output: realms/aws-databricks/bundle/databricks.yml and, per domain,
bundle/resources/<domain>__platform.yml and <domain>__proof.yml, byte-identical for the same input (sorted, fixed
formatting), so CI can fail on a stale bundle.

Per domain, the shape proven in realms/databricks/v1:
    <domain>__platform   one job, three tasks in a chain: ingestion, silver, gold (scripts/run_hop.py through
                         realms/databricks/v1/tasks/hop.py). Its `window` parameter is the business date to load;
                         left empty, the task takes today's date in the domain's business timezone. A daily schedule
                         is declared and deployed paused: V1 loads every dataset in one daily run, and the per-dataset
                         schedules in the manifest become per-cadence jobs after V1.
    <domain>__proof      the proof driver: the simulated world, N days, against the deployed platform job, judged
                         against the world's known answers. It is the integration test `make integration` runs.
Names follow ADR-012: catalogs <env>_<layer>.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

import yaml

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
COMPILED = REPO / "realms" / "databricks" / "compiled" / "domains"
OUT = HERE / "bundle"
HEADER = ("# GENERATED by realms/aws-databricks/generate_bundle.py from realms/databricks/compiled/domains/. "
          "Do not edit.\n")
NAME = re.compile(r"^[a-z][a-z0-9_]*$")

# The Databricks Free Edition workspace (stack variant "AWS account + Databricks Free Edition", DEPLOYED.md): the
# free-dev target is dev pinned to it, so a deploy cannot land in another workspace by a stray DATABRICKS_HOST.
FREE_EDITION_HOST = "https://dbc-00000000-0000.cloud.databricks.com"

# Paths as seen from bundle/resources/*.yml (resource paths resolve relative to the file that names them).
TASKS = "../../../databricks/v1/tasks"
# The spec catalog slice, copied beside the bundle before a deploy (make bundle); the tasks read it from here.
CATALOG_DIR = "${workspace.file_path}/realms/aws-databricks/bundle/_catalog"
HOPS = ("ingest", "silver", "gold")
DAILY = "0 0 1 * * ?"  # 01:00 in the domain's business timezone
ENVIRONMENT = [{"environment_key": "default",
                "spec": {"environment_version": "3", "dependencies": ["psycopg[binary]>=3.2", "pyyaml>=6"]}}]


class BundleError(ValueError):
    pass


def check(domain: dict[str, Any]) -> str:
    """The domain's name, after the checks that stop a generation: a safe name, a timezone, at least one dataset."""
    name = domain.get("domain", "")
    if not NAME.match(name):
        raise BundleError(f"domain '{name}' is not lower snake case (ADR-012 naming)")
    if not domain.get("business_timezone"):
        raise BundleError(f"domain {name}: no business_timezone, so a run cannot tell which business date it loads")
    if not any(d.get("is_enabled", True) for d in domain.get("datasets", [])):
        raise BundleError(f"domain {name}: no enabled dataset; there is nothing to load")
    for d in domain["datasets"]:
        for part in (d["source"], d["dataset"]):
            if not NAME.match(part):
                raise BundleError(f"'{part}' is not lower snake case (ADR-012 naming)")
    return name


def common(domain: dict[str, Any]) -> list[str]:
    """Task parameters every V1 task takes."""
    return ["--env", "${var.env}", "--meta-instance", "${var.meta_instance}", "--meta-database",
            "${var.meta_database}", "--catalog-dir", CATALOG_DIR, "--root", "${workspace.file_path}"]


def hop_task(domain: dict[str, Any], hop: str, depends_on: str | None) -> dict[str, Any]:
    t: dict[str, Any] = {
        "task_key": hop,
        "environment_key": "default",
        "spark_python_task": {
            "python_file": f"{TASKS}/hop.py",
            "parameters": ["--hop", hop, "--window", "{{job.parameters.window}}", "--business-tz",
                           domain["business_timezone"], "--secret-scope", "${var.secret_scope}", *common(domain)],
        },
    }
    if depends_on:
        t["depends_on"] = [{"task_key": depends_on}]
    return t


def tags(domain: dict[str, Any]) -> dict[str, str]:
    return {"env": "${var.env}", "domain": domain["domain"], "cost_center": "${var.cost_center}"}


def platform_job(domain: dict[str, Any]) -> dict[str, Any]:
    name = check(domain)
    tasks = [hop_task(domain, hop, HOPS[i - 1] if i else None) for i, hop in enumerate(HOPS)]
    job = {
        "name": f"dp-${{var.env}}-{name}-platform",
        "max_concurrent_runs": 1,
        "queue": {"enabled": True},
        "tags": tags(domain),
        "parameters": [{"name": "window", "default": ""}],
        "schedule": {"quartz_cron_expression": DAILY, "timezone_id": domain["business_timezone"],
                     "pause_status": "PAUSED"},
        "environments": ENVIRONMENT,
        "tasks": tasks,
    }
    return {"resources": {"jobs": {f"{name}__platform": job}}}


def proof_job(domain: dict[str, Any]) -> dict[str, Any]:
    name = check(domain)
    driver = {
        "task_key": "days",
        "environment_key": "default",
        "spark_python_task": {
            "python_file": f"{TASKS}/driver.py",
            "parameters": ["--days", "{{job.parameters.days}}", "--calendar", "{{job.parameters.calendar}}",
                           "--housekeeping-days", "{{job.parameters.housekeeping_days}}", "--platform-job-id",
                           f"${{resources.jobs.{name}__platform.id}}", "--run-id", "{{job.run_id}}", *common(domain)],
        },
    }
    job = {
        "name": f"dp-${{var.env}}-{name}-proof",
        "max_concurrent_runs": 1,
        "tags": tags(domain),
        "parameters": [{"name": "days", "default": "3"}, {"name": "calendar", "default": "compressed"},
                       {"name": "housekeeping_days", "default": "1"}],
        "environments": ENVIRONMENT,
        "tasks": [driver],
    }
    return {"resources": {"jobs": {f"{name}__proof": job}}}


def target(env: str, host: str | None = None) -> dict[str, Any]:
    # One copy per deploying identity (the CI service principal), never a folder shared by all users.
    workspace = {"host": host} if host else {}
    workspace["root_path"] = "/Workspace/Users/${workspace.current_user.userName}/.bundle/${bundle.name}/" + env
    return {"mode": "production",
            "variables": {"env": env, "meta_instance": f"dp-meta-{env}", "secret_scope": f"dp-{env}"},
            "workspace": workspace}


def root() -> dict[str, Any]:
    return {
        "bundle": {"name": "dp_aws"},
        "include": ["resources/*.yml"],
        "variables": {
            "env": {"description": "dev or prod; picks the catalogs <env>_<layer>"},
            "cost_center": {"default": "data-platform"},
            "meta_instance": {"description": "the Lakebase instance that holds the metadata store"},
            "meta_database": {"description": "the metadata database the platform and proof jobs share; the proof "
                                             "run empties it, so never the live store", "default": "dp_meta_proof"},
            "secret_scope": {"description": "the secret scope that holds token-key"},
        },
        "sync": {"paths": ["../../../src/dataplatform", "../../../scripts", "../../../models", "../../databricks/v1",
                           "."],
                 "include": ["_catalog/**"]},
        # The workspace host is not written here: CI sets DATABRICKS_HOST per GitHub environment (Terraform output
        # workspace_url), so the same bundle deploys to either workspace.
        "targets": {
            "dev": {"default": True, **target("dev")},
            "prod": target("prod"),
            # Free Edition: serverless only, which every generated job already is (no cluster specs).
            "free-dev": target("dev", FREE_EDITION_HOST),
        },
    }


def dump(doc: dict[str, Any]) -> str:
    return HEADER + yaml.safe_dump(doc, sort_keys=False, default_flow_style=False, width=120)


def generate(compiled_dir: Path = COMPILED) -> dict[str, str]:
    """Relative output path -> file text. Pure: reads the compiled JSON, writes nothing."""
    files = {"databricks.yml": dump(root())}
    for path in sorted(compiled_dir.glob("*.json")):
        domain = json.loads(path.read_text())
        name = check(domain)
        files[f"resources/{name}__platform.yml"] = dump(platform_job(domain))
        files[f"resources/{name}__proof.yml"] = dump(proof_job(domain))
    return files


def main() -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--check", action="store_true", help="fail if the committed bundle differs from the manifests")
    a = p.parse_args()
    files = generate()
    stale = sorted(n for n, text in files.items() if not (OUT / n).exists() or (OUT / n).read_text() != text)
    extra = sorted(str(f.relative_to(OUT)) for f in (OUT / "resources").glob("*.yml")
                   if str(f.relative_to(OUT)) not in files) if (OUT / "resources").exists() else []
    if a.check:
        for n in stale + extra:
            sys.stderr.write(f"stale: realms/aws-databricks/bundle/{n}\n")
        return 1 if stale or extra else 0
    for n, text in files.items():
        (OUT / n).parent.mkdir(parents=True, exist_ok=True)
        (OUT / n).write_text(text)
    for n in extra:
        (OUT / n).unlink()
    sys.stdout.write(f"wrote {len(files)} files to realms/aws-databricks/bundle/\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
