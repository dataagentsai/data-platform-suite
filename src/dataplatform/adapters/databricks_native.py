"""Databricks bindings for the adopted platform-native screens and notifications (dataplatform.obs.native).

Nothing here rebuilds a native screen: each entry is a reference the realm imports or links, rendered into
realms/databricks/dashboards/native.yml by the dashboards generator (golden file, drift-checked).

    jobs_monitoring           the platform's Lakeflow job health dashboard over `system.lakeflow` and billing, kept
                              unchanged in realms/databricks/dashboards/native/ and deployed by the bundle; not generated
    job_failure_notification  `webhook_notifications.on_failure` with the workspace's notification destination, plus
                              `email_notifications.on_failure` to the job's owners: a snippet for every generated job
                              (JOB_NOTIFICATIONS; merging it into the bundle generator is pending, see obs/README.md)
    lineage_view              Catalog Explorer > Lineage on each table
    audit_view                the `system.access.audit` table, browsed in Catalog Explorer or queried on demand
    table_insights            Catalog Explorer > Insights on each table (readers, frequent queries and joins)
    anomaly_detection         data quality monitoring's anomaly detection, enabled per schema (freshness, completeness);
                              works on Free Edition (checked 13 Nov on dev_silver.erp)
"""

from __future__ import annotations

from dataplatform.obs.native import NATIVE

BINDINGS: dict[str, dict[str, str]] = {
    "jobs_monitoring": {
        "how": "deploy unchanged",
        "where": "realms/databricks/dashboards/native/lakeflow_job_health.lvdash.json: the platform's Lakeflow job "
                 "health template, exported as is (imported 4 Nov) and deployed by the dashboards bundle",
        "reads": "system.lakeflow.jobs, system.lakeflow.job_run_timeline, system.lakeflow.job_task_run_timeline",
    },
    "job_failure_notification": {
        "how": "job setting",
        "where": "every job: webhook_notifications.on_failure -> ${var.ops_destination_id}; "
                 "email_notifications.on_failure -> the job's owners",
        "reads": "the job's own run events",
    },
    "lineage_view": {"how": "link", "where": "Catalog Explorer > <table> > Lineage",
                     "reads": "system.access.table_lineage, system.access.column_lineage"},
    "audit_view": {"how": "link", "where": "Catalog Explorer > system.access.audit", "reads": "system.access.audit"},
    "table_insights": {"how": "link", "where": "Catalog Explorer > <table> > Insights",
                       "reads": "system.query.history, system.access.audit"},
    "anomaly_detection": {"how": "enable per schema",
                          "where": "Catalog Explorer > <schema> > Details > Data quality monitoring; enabled by "
                                   "realms/databricks/dashboards/enable_anomaly_detection.py on the silver and gold "
                                   "schemas",
                          "reads": "the watched tables' commit history (results in system.data_quality_monitoring)"},
}

JOB_NOTIFICATIONS = {
    "webhook_notifications": {"on_failure": [{"id": "${var.ops_destination_id}"}]},
    "email_notifications": {"on_failure": ["${var.ops_owner_email}"], "no_alert_for_skipped_runs": True},
}


def render_native_yaml() -> str:
    """The adopted set as a deterministic YAML file (no YAML library: plain, sorted, quoted)."""
    lines = ["# Generated by realms/databricks/dashboards/generate.py from dataplatform.obs.native. Do not edit.",
             "# Platform-native screens and notifications, adopted, not rebuilt (ADR-024 rule 1, set a).",
             "native:"]
    for n in NATIVE:
        b = BINDINGS[n.id]
        lines += [f"  {n.id}:", f"    kind: {n.kind}", f'    how: "{b["how"]}"', f'    where: "{b["where"]}"',
                  f'    reads: "{b["reads"]}"', f'    covers: "{n.covers}"', f'    instead_of: "{n.instead_of}"']
    lines += ["# For every generated job (merging into the bundle generator is pending):", "job_notifications:",
              "  webhook_notifications:", "    on_failure:", '      - id: "${var.ops_destination_id}"',
              "  email_notifications:", "    on_failure:", '      - "${var.ops_owner_email}"',
              "    no_alert_for_skipped_runs: true"]
    return "\n".join(lines) + "\n"
