"""The ops metric views (dataplatform.obs.views) as Databricks metric views: one `CREATE ... WITH METRICS` per view.

The same shape the business metric views take (realms/databricks/semantic_governance, W5): YAML 1.1 inside the
view, a source table, dimensions and measures with comments. Generated into realms/databricks/dashboards/views/ by
the dashboards generator, committed and drift-checked; every name passes the plain-name rule before it is written.
"""

from __future__ import annotations

import json
import re

from dataplatform.obs.views import OpsView, ViewMeasure

_NAME = re.compile(r"^[A-Za-z_][A-Za-z0-9_]{0,62}$")
HEADER = "-- GENERATED by realms/databricks/dashboards/generate.py from dataplatform.obs.views. Do not edit.\n"


def _plain(name: str) -> str:
    if not _NAME.match(name):
        raise ValueError(f"not a plain name: {name!r}")
    return name


def _q(text: str) -> str:
    return json.dumps(text)  # a double-quoted YAML scalar


def measure_expr(m: ViewMeasure) -> str:
    if m.agg == "count":
        return "COUNT(1)"
    col = f"`{_plain(m.column)}`"
    if m.agg == "count_distinct":
        return f"COUNT(DISTINCT {col})"
    return f"{m.agg.upper()}({col})"


def view_yaml(v: OpsView, catalog: str, schema: str) -> str:
    lines = ["version: 1.1", f"comment: {_q(v.comment + ' Certified ops definition (ADR-024 rule 7).')}",
             f"source: {_plain(catalog)}.{_plain(schema)}.{_plain(v.table)}", "dimensions:"]
    for d in v.dimensions:
        lines += [f"  - name: {_plain(d)}", f"    expr: {_q(f'`{_plain(d)}`')}"]
    lines.append("measures:")
    for m in v.measures:
        lines += [f"  - name: {_plain(m.name)}", f"    expr: {_q(measure_expr(m))}"]
        if m.comment:
            lines.append(f"    comment: {_q(m.comment)}")
    return "\n".join(lines) + "\n"


def view_sql(v: OpsView, catalog: str, schema: str) -> str:
    name = f"`{_plain(catalog)}`.`{_plain(schema)}`.`{_plain(v.name)}`"
    return (HEADER + f"-- {v.name}: over {v.table}\nCREATE OR REPLACE VIEW {name}\nWITH METRICS\nLANGUAGE YAML\n"
            f"AS $$\n{view_yaml(v, catalog, schema)}$$;\n")
