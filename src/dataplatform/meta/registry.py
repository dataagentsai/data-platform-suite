"""The settings registry (DPC-0034): every key a manifest may set, with its scope, type and default.

settings_registry.json is generated by scripts/export_settings_registry.py from LakeIngestionFramework's key registry
plus the keys the spec catalog proposes; do not edit it by hand.
"""

from __future__ import annotations

import json
from pathlib import Path

from dataplatform.meta.port import SettingDef

PATH = Path(__file__).with_name("settings_registry.json")


def load(path: Path = PATH) -> list[SettingDef]:
    rows = json.loads(path.read_text())
    return [SettingDef(key=r["key"], scope=r["scope"], value_type=r["value_type"], default=r["default"],
                       allowed=tuple(r["allowed"]) if r["allowed"] else None, description=r["description"],
                       status=r["status"]) for r in rows]


def by_key(defs: list[SettingDef], scope: str) -> dict[str, SettingDef]:
    return {d.key: d for d in defs if d.scope == scope}


def type_problem(d: SettingDef, value: str) -> str | None:
    """Why a value does not fit its registered type, or None. The loader reports these; unknown keys it refuses."""
    if d.allowed and value not in d.allowed:
        return f"{d.key}={value!r} is not one of {', '.join(d.allowed)}"
    if d.value_type == "int":
        try:
            int(value)
        except ValueError:
            return f"{d.key}={value!r} is not a whole number"
    if d.value_type == "bool" and value.lower() not in ("true", "false"):
        return f"{d.key}={value!r} is not true or false"
    return None
